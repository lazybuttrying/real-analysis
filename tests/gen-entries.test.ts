import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import type { ChapterMeta } from '../src/contracts';
import { entryHtml, syncChapterEntries } from '../scripts/gen-entries';

const chapter = (id: string): ChapterMeta => ({
  id,
  title: { ko: `${id} 챕터`, en: `${id} chapter` },
  summary: { ko: '요약', en: 'Summary' },
  scenes: [],
});

const tempRoot = (): string => mkdtempSync(join(tmpdir(), 'gen-entries-'));

describe('entryHtml', () => {
  it('boots the chapter entry module; one entry serves both languages', () => {
    const html = entryHtml(chapter('series'));
    expect(html).toContain('/src/chapters/series/entry.ts');
    expect(html).toContain('generated by scripts/gen-entries.ts');
    expect(html).toContain('series 챕터');
  });
});

describe('syncChapterEntries', () => {
  it('creates one entry per chapter and registers each in the .gitignore block', () => {
    const root = tempRoot();
    syncChapterEntries(root, [chapter('series'), chapter('fourier')]);

    for (const id of ['series', 'fourier']) {
      const file = join(root, id, 'index.html');
      expect(existsSync(file)).toBe(true);
      expect(readFileSync(file, 'utf8')).toContain(`/src/chapters/${id}/entry.ts`);
    }
    const gitignore = readFileSync(join(root, '.gitignore'), 'utf8');
    expect(gitignore).toContain('/series/');
    expect(gitignore).toContain('/fourier/');
  });

  it('is idempotent: a second run leaves files unchanged', () => {
    const root = tempRoot();
    syncChapterEntries(root, [chapter('series')]);
    const before = readFileSync(join(root, 'series', 'index.html'), 'utf8');
    syncChapterEntries(root, [chapter('series')]);
    expect(readFileSync(join(root, 'series', 'index.html'), 'utf8')).toBe(before);
  });

  it('rejects reserved ids', () => {
    for (const id of ['src', 'docs', 'assets', 'dist']) {
      expect(() => syncChapterEntries(tempRoot(), [chapter(id)])).toThrow();
    }
  });

  it('rejects ids outside lowercase letters, digits, and hyphens', () => {
    for (const id of ['Series', 'my chapter', 'a/b', '9lives']) {
      expect(() => syncChapterEntries(tempRoot(), [chapter(id)])).toThrow();
    }
  });

  it('rejects duplicate chapter ids', () => {
    expect(() => syncChapterEntries(tempRoot(), [chapter('series'), chapter('series')])).toThrow();
  });

  it('refuses to write into a folder that holds hand-written files', () => {
    const root = tempRoot();
    mkdirSync(join(root, 'series'), { recursive: true });
    writeFileSync(join(root, 'series', 'notes.txt'), 'mine');
    expect(() => syncChapterEntries(root, [chapter('series')])).toThrow();
  });
});
