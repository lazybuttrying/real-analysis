import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { ChapterMeta } from '../src/contracts.ts';

/**
 * catalog의 챕터마다 Vite 진입점 <챕터>/index.html 을 생성한다.
 * 생성물은 .gitignore 의 관리 블록에 등록되어 저장소에는 남지 않는다.
 * vite.config.ts 의 config 단계에서 호출되므로 dev, build, preview 어느 쪽이든 먼저 실행된다.
 */

const MARKER = '<!-- generated by scripts/gen-entries.ts: 직접 수정하지 마세요 -->';
const GITIGNORE_BEGIN = '# >>> generated chapter entries (scripts/gen-entries.ts) >>>';
const GITIGNORE_END = '# <<< generated chapter entries <<<';

const ID_PATTERN = /^[a-z][a-z0-9-]*$/;

/** 프로젝트 폴더나 Vite 출력과 겹치는 이름은 챕터 id로 쓸 수 없다. (.gitignore 에 /<id>/ 가 등록되므로 특히 중요) */
const RESERVED_IDS = new Set(['src', 'scripts', 'docs', 'public', 'dist', 'node_modules', 'assets', 'home']);

const escapeHtml = (text: string): string =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const escapeRegExp = (text: string): string => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export function entryHtml(chapter: ChapterMeta): string {
  return `<!doctype html>
<html lang="ko">
  <head>
    ${MARKER}
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${escapeHtml(chapter.title)}</title>
  </head>
  <body>
    <div id="app"></div>
    <script type="module" src="/src/chapters/${chapter.id}/entry.ts"></script>
  </body>
</html>
`;
}

function assertValidId(id: string): void {
  if (!ID_PATTERN.test(id)) {
    throw new Error(`[gen-entries] 챕터 id는 소문자, 숫자, 하이픈만 쓸 수 있습니다: "${id}"`);
  }
  if (RESERVED_IDS.has(id)) {
    throw new Error(`[gen-entries] 예약된 이름은 챕터 id로 쓸 수 없습니다: "${id}"`);
  }
}

/** 내용이 같으면 쓰지 않는다. (dev 서버가 불필요하게 다시 로드되는 것을 막는다) */
function writeIfChanged(file: string, content: string): void {
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return;
  writeFileSync(file, content);
}

function writeEntry(root: string, chapter: ChapterMeta): void {
  const dir = join(root, chapter.id);
  const file = join(dir, 'index.html');

  if (existsSync(dir)) {
    const others = readdirSync(dir).filter((name) => name !== 'index.html');
    if (others.length > 0) {
      throw new Error(`[gen-entries] "${chapter.id}/" 에 생성 파일이 아닌 파일이 있습니다: ${others.join(', ')}`);
    }
    if (existsSync(file) && !readFileSync(file, 'utf8').includes(MARKER)) {
      throw new Error(`[gen-entries] "${chapter.id}/index.html" 은 직접 작성된 파일이라 덮어쓰지 않습니다`);
    }
  } else {
    mkdirSync(dir, { recursive: true });
  }
  writeIfChanged(file, entryHtml(chapter));
}

function syncGitignore(root: string, ids: readonly string[]): void {
  const file = join(root, '.gitignore');
  const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const block = [GITIGNORE_BEGIN, ...ids.map((id) => `/${id}/`), GITIGNORE_END].join('\n');
  const managed = new RegExp(`${escapeRegExp(GITIGNORE_BEGIN)}[\\s\\S]*?${escapeRegExp(GITIGNORE_END)}`);

  const next = managed.test(current)
    ? current.replace(managed, () => block)
    : `${current.replace(/\n*$/, '\n')}\n${block}\n`;
  writeIfChanged(file, next);
}

export function syncChapterEntries(root: string, chapters: readonly ChapterMeta[]): void {
  const ids = chapters.map((chapter) => chapter.id);
  if (new Set(ids).size !== ids.length) {
    throw new Error('[gen-entries] 챕터 id가 중복되었습니다');
  }
  // 하나라도 잘못되면 아무것도 쓰기 전에 실패시킨다.
  ids.forEach(assertValidId);

  chapters.forEach((chapter) => writeEntry(root, chapter));
  syncGitignore(root, ids);
}
